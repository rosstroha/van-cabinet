import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const out=path.join(path.dirname(fileURLToPath(import.meta.url)),'dist');
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { chromium } from 'playwright';
const base='http://127.0.0.1:8765';
const cached=path.join(homedir(),'.cache/ms-playwright/chromium-1243/chrome-linux64/chrome');
const browser=await chromium.launch({headless:true,executablePath:process.env.CABINET_BROWSER_PATH||(existsSync(cached)?cached:chromium.executablePath()),args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[],external=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('request',r=>{const u=new URL(r.url());if(['http:','https:'].includes(u.protocol)&&u.origin!==base)external.push(u.href);});
const state=()=>page.evaluate(()=>window.__cabinetViewer.getState());
const part=name=>page.evaluate(name=>window.__cabinetViewer.getPart(name),name);
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-6,`${a} != ${b}`);
const range=(id,value)=>page.locator(`#${id}`).evaluate((el,value)=>{el.value=String(value);el.dispatchEvent(new Event('input',{bubbles:true}));},value);
const settle=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
try{
 await mkdir(out,{recursive:true});
 await page.goto(base,{waitUntil:'networkidle'});
 await page.waitForFunction(()=>window.__cabinetViewer&&document.querySelector('#loading').hidden);
 const model=await page.evaluate(async()=>(await fetch('./model.json')).json());
 assert.equal((await state()).partCount,model.parts.length);
 assert.equal(await page.locator('#part-select option').count(),model.parts.length+1);
 await page.locator('[data-view="front"]').click();await settle();
 assert.ok((await part('VA930_sink_reserved_envelope')).screen[0]<(await part('toilet_335_reserved_envelope')).screen[0],'Sink must be left of toilet');
 const canvas=await page.locator('#canvas-host canvas').boundingBox(),projected=(await part('tank_access_door')).screen;
 await page.mouse.click(canvas.x+(projected[0]+1)*canvas.width/2,canvas.y+(1-projected[1])*canvas.height/2);
 assert.equal((await state()).selected,'tank_access_door','Canvas raycast selection');
 const doorIndex=model.parts.findIndex(p=>p.name==='toilet_hinged_door');
 await page.selectOption('#part-select',String(doorIndex));assert.equal((await state()).selected,'toilet_hinged_door');
 assert.match(await page.locator('#part-name').innerText(),/Toilet Hinged Door/);
 assert.match(await page.locator('#part-size').innerText(),/W × D × H/);
 await page.locator('#reset').click();await page.locator('.sidebar').evaluate(el=>el.scrollTop=0);await settle();await page.screenshot({path:path.join(out,'qa-desktop-stowed.png')});
 const beforeToilet=await part('toilet_sled'),beforeDog=await part('dog_deck');
 await range('toilet',9);assert.equal((await state()).toilet,9);assert.equal((await state()).door,95);
 await range('dog',6);assert.equal((await state()).dog,6);
 await page.locator('#deployed').click();
 close((await part('toilet_sled')).position[1]-beforeToilet.position[1],-18);
 close((await part('dog_deck')).position[1]-beforeDog.position[1],-12);
 close((await part('toilet_hinged_door')).rotation,95*Math.PI/180);
 await page.locator('#fronts').uncheck();await page.locator('#top').uncheck();
 for(const name of ['tank_access_door','toilet_hinged_door','countertop'])assert.equal((await part(name)).visible,false);
 await page.locator('#dimensions').check();assert.equal((await state()).dimensions,true);
 await page.locator('[data-view="iso"]').click();await settle();await page.screenshot({path:path.join(out,'qa-desktop-extended-interior.png')});
 await page.locator('#envelopes').uncheck();
 for(const p of model.parts.filter(p=>['toilet','tank','sink'].includes(p.kind)))assert.equal((await part(p.name)).visible,false,p.name);
 await page.selectOption('#part-select',String(doorIndex));assert.equal((await state()).fronts,true);assert.equal((await part('toilet_hinged_door')).visible,true);
 const unexploded=await part('left_side');await range('explode',3);assert.notDeepEqual((await part('left_side')).position,unexploded.position);
 await page.locator('#stowed').click();const stowed=await state();assert.equal(stowed.toilet+stowed.dog+stowed.door,0);
 await page.locator('[data-view="top"]').click();await settle();assert.ok((await part('VA930_sink_reserved_envelope')).screen[0]<(await part('toilet_335_reserved_envelope')).screen[0],'Top view keeps sink on left');assert.equal(await page.locator('[data-view="top"]').getAttribute('aria-pressed'),'true');
 await page.locator('#reset').click();
 assert.deepEqual(await state(),{toilet:0,dog:0,door:0,explode:0,fronts:true,top:true,envelopes:true,dimensions:false,partCount:model.parts.length,selected:null});
 await page.setViewportSize({width:390,height:844});await page.locator('.sidebar').evaluate(el=>el.scrollTop=0);await page.locator('[data-view="iso"]').click();await settle();await page.evaluate(()=>window.scrollTo(0,0));
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile horizontal overflow');
 const mobileCanvas=await page.locator('#canvas-host canvas').boundingBox();assert.ok(mobileCanvas.width>300&&mobileCanvas.height>=250);
 await page.screenshot({path:path.join(out,'qa-mobile.png')});
 assert.deepEqual(errors,[],'Browser errors');assert.deepEqual(external,[],'External requests');
 console.log(`PASS: ${model.parts.length} parts, orientation, selection, motion, visibility, views, reset, mobile, and local assets.`);
}finally{await browser.close();}
